const field = (name: string, type: string, extra: Partial<DmmfField> = {}): DmmfField => ({
  name,
  kind: "scalar",
  type,
  isList: false,
  isRequired: true,
  hasDefaultValue: false,
  ...extra,
});

const datamodel: DmmfDatamodel = {
  enums: [
    { name: "Role", dbName: null, values: [{ name: "ADMIN", dbName: null }, { name: "GUEST", dbName: "guest" }] },
    { name: "Status", dbName: "account_status", values: [{ name: "ON", dbName: null }] },
  ],
  models: [
    {
      name: "User",
      dbName: "users",
      schema: null,
      fields: [
        field("id", "Int", { hasDefaultValue: true, default: { name: "autoincrement", args: [] } }),
        field("email", "String", { nativeType: ["VarChar", ["200"]] }),
        field("name", "String", { dbName: "display name", isRequired: false }),
        field("role", "Role", { kind: "enum", hasDefaultValue: true, default: "ADMIN" }),
        field("roles", "Role", { kind: "enum", isList: true }),
        field("updatedAt", "DateTime", { isUpdatedAt: true, documentation: "Last change." }),
        field("posts", "Post", { kind: "object", isList: true }),
      ],
    },
    {
      name: "Account",
      dbName: null,
      schema: "auth",
      fields: [
        field("id", "String", { hasDefaultValue: true, default: { name: "uuid", args: [4] }, nativeType: ["Uuid", []] }),
        field("status", "Status", { kind: "enum" }),
        field("at", "DateTime", { nativeType: ["Timestamptz", ["6"]], hasDefaultValue: true, default: { name: "now", args: [] } }),
      ],
    },
    { name: "Active", dbName: "active_users", schema: "public", fields: [field("id", "Int")] },
  ],
};

describe("generateSource", () => {
  test("emits the TypeSQL schema", () => {
    expect(generateSource(datamodel, { views: ["Active"], importFrom: "@typesql/core", typeName: "Database" })).toBe(`// Generated by @typesql/prisma from the Prisma schema. Do not edit.
import type { Col, Nullable, Generated, View } from "@typesql/core";

export interface Database {
  /** Prisma model \`User\`. */
  users: {
    id: Generated<"int4">;
    email: Col<"varchar">;
    /** Prisma field \`name\`. */
    "display name": Nullable<"text">;
    role: Generated<"Role">;
    roles: Nullable<"Role[]">;
    /**
     * \`@updatedAt\`: set by Prisma Client, no database default.
     * Last change.
     */
    updatedAt: Col<"timestamp">;
  };
  /** Prisma view \`Active\`. */
  active_users: View<{
    id: Col<"int4">;
  }>;
  auth: {
    Account: {
      id: Col<"uuid">;
      status: Col<"account_status">;
      at: Generated<"timestamptz">;
    };
  };
  $types: {
    Role: "ADMIN" | "guest";
    /** Prisma enum \`Status\`. */
    account_status: "ON";
  };
}
`);
  });

  test("an empty datamodel yields an empty interface", () => {
    expect(generateSource({ models: [], enums: [] })).toBe(
      "// Generated by @typesql/prisma from the Prisma schema. Do not edit.\n\nexport interface DB {\n}\n",
    );
  });

  test("database defaults: literals and DB-side functions count, client-side functions do not", () => {
    const def = (d: Exclude<DmmfField["default"], undefined>) => hasDbDefault(field("x", "String", { hasDefaultValue: true, default: d }));
    expect([def("x"), def(0), def(false), def([]), def({ name: "now", args: [] }), def({ name: "dbgenerated", args: [] })]).toEqual([true, true, true, true, true, true]);
    expect([def({ name: "uuid", args: [4] }), def({ name: "cuid", args: [2] }), def({ name: "nanoid", args: [] }), def({ name: "ulid", args: [] })]).toEqual([false, false, false, false]);
    expect(hasDbDefault(field("x", "DateTime", { isUpdatedAt: true }))).toBe(false);
  });
});

test("viewNames finds view blocks", () => {
  expect(viewNames("model A {\n}\nview  B {\n  id Int\n}\n  view C{\n}\n// view D {\n")).toEqual(["B", "C"]);
});

test("outputFile: a .ts path is the file, anything else a directory", () => {
  expect(outputFile("/x/db.ts")).toBe("/x/db.ts");
  expect(outputFile("/x/db.mts")).toBe("/x/db.mts");
  expect(outputFile("/x/generated")).toBe("/x/generated/index.ts");
});

const options = (provider: string, config: GeneratorOptions["generator"]["config"] = {}): GeneratorOptions => ({
  generator: { name: "typesql", output: { value: "/x/db.ts" }, config },
  datamodel: "",
  dmmf: { datamodel: { models: [], enums: [] } },
  schemaPath: "/x/schema.prisma",
  datasources: [{ provider, activeProvider: provider }],
});

test("sourceFor reads the generator config and rejects other providers", () => {
  expect(sourceFor(options("postgresql", { typeName: "Schema" }))).toContain("export interface Schema {");
  expect(() => sourceFor(options("mysql"))).toThrow(/only the postgresql provider/);
});

describe("serveGenerator", () => {
  async function exchange(handler: GeneratorHandler, requests: readonly string[]): Promise<unknown[]> {
    const input = new PassThrough();
    const output = new PassThrough();
    let text = "";
    output.on("data", (chunk: Buffer) => (text += chunk.toString()));
    const done = serveGenerator(handler, input, output);
    for (const r of requests) input.write(r + "\n");
    input.end();
    await done;
    return text.trim().split("\n").map((l) => (l.startsWith("{") ? JSON.parse(l) : l));
  }

  test("answers getManifest and generate on the output stream, one JSON line each", async () => {
    const seen: string[] = [];
    const handler: GeneratorHandler = {
      onManifest: (config) => (seen.push(config.name), { prettyName: "x" }),
      onGenerate: async (o) => void seen.push(o.schemaPath),
    };
    const res = await exchange(handler, [
      JSON.stringify({ jsonrpc: "2.0", id: 1, method: "getManifest", params: { name: "typesql" } }),
      JSON.stringify({ jsonrpc: "2.0", id: 2, method: "generate", params: { schemaPath: "/s.prisma" } }),
    ]);
    expect(res).toEqual([
      { jsonrpc: "2.0", id: 1, result: { manifest: { prettyName: "x" } } },
      { jsonrpc: "2.0", id: 2, result: null },
    ]);
    expect(seen).toEqual(["typesql", "/s.prisma"]);
  });

  test("reports handler failures and unknown methods as JSON-RPC errors", async () => {
    const handler: GeneratorHandler = {
      onManifest: () => ({}),
      onGenerate: () => {
        throw new Error("boom");
      },
    };
    const res = await exchange(handler, [
      JSON.stringify({ jsonrpc: "2.0", id: 7, method: "generate", params: {} }),
      JSON.stringify({ jsonrpc: "2.0", id: 8, method: "nope", params: {} }),
      "not json",
    ]);
    // Responses are matched by id, so their order does not matter.
    expect(res).toHaveLength(3);
    expect(res).toContainEqual({ jsonrpc: "2.0", id: 7, error: { code: -32000, message: "boom", data: { stack: expect.stringContaining("boom") } } });
    expect(res).toContainEqual({ jsonrpc: "2.0", id: 8, error: { code: -32601, message: "Method not found: nope" } });
    expect(res).toContain("typesql-prisma: ignoring a request that is not JSON: not json");
  });
});

const pkg = fileURLToPath(new URL("..", import.meta.url));
const run = promisify(execFile);

test("prisma generate runs the generator end to end", { timeout: 60_000 }, async () => {
  // A copy of the fixture schema, so the output lands in a temporary directory.
  const dir = await mkdtemp(join(tmpdir(), "typesql-prisma-"));
  try {
    await copyFile(join(pkg, "test/fixtures/schema.prisma"), join(dir, "schema.prisma"));
    const prisma = join(pkg, "node_modules/.bin/prisma");
    const { stdout } = await run(prisma, ["generate", "--schema", join(dir, "schema.prisma"), "--generator", "typesql", "--no-hints"], {
      cwd: pkg,
      env: { ...process.env, CHECKPOINT_DISABLE: "1" },
    });
    expect(stdout).toContain("Generated TypeSQL schema");
    await expect(await readFile(join(dir, "typesql.ts"), "utf8")).toMatchFileSnapshot("./fixtures/typesql.ts");
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
