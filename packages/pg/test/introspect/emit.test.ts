import { describe, expect, test } from "vitest";
import { generateSource, type IntrospectedColumn, type IntrospectedDatabase } from "../../src/introspect/index.js";
import { main } from "../../src/introspect/cli.js";
import { parseNodeTree } from "../../src/introspect/nullability.js";

const col = (name: string, type: string, extra: Partial<IntrospectedColumn> = {}): IntrospectedColumn => ({
  name, type, declaredType: type, domain: null, nullable: false, hasDefault: false,
  identity: null, generated: null, default: null, comment: null, ...extra,
});

const db = (over: Partial<IntrospectedDatabase> = {}): IntrospectedDatabase => ({
  version: "17.2 (Debian 17.2-1)",
  schemas: ["public"],
  relations: [{ schema: "public", name: "t", kind: "table", comment: null, columns: [col("id", "int4", { hasDefault: true }), col("doc", "jsonb", { nullable: true })] }],
  enums: [],
  ...over,
});

describe("generateSource", () => {
  test("helpers, quoting and the header", () => {
    const source = generateSource(db({
      schemas: ["public", "my-schema"],
      relations: [
        { schema: "public", name: "user-data", kind: "table", comment: null, columns: [col("a:b", "text", { nullable: true, hasDefault: true }), col("$x", "int8")] },
        { schema: "my-schema", name: "v", kind: "view", comment: null, columns: [col("n", "int8", { nullable: true })] },
      ],
    }), { typeName: "Schema", importFrom: "./core.js", comments: false });
    expect(source).toBe(`// Generated by \`typesql introspect\` (@typesql/pg) from PostgreSQL 17. Do not edit.
import type { Col, Nullable, NullableGenerated, View } from "./core.js";

export interface Schema {
  "user-data": {
    "a:b": NullableGenerated<"text">;
    $x: Col<"int8">;
  };
  "my-schema": {
    v: View<{
      n: Nullable<"int8">;
    }>;
  };
}
`);
  });

  test("columnTypes declare json / jsonb columns as Json<T>; unknown keys and other columns are an error", () => {
    const source = generateSource(db({
      relations: [{
        schema: "public", name: "t", kind: "table", comment: null, columns: [
          col("id", "int4", { hasDefault: true }),
          col("doc", "jsonb", { nullable: true }),
          col("items", "jsonb", { hasDefault: true }),
          col("both", "jsonb", { nullable: true, hasDefault: true }),
          col("plain", "jsonb"),
          col("raw", "json"),
          col("raw_null", "json", { nullable: true }),
          col("other", "jsonb"),
        ],
      }],
    }), {
      columnTypes: { "t.doc": "{ a: number }", "t.items": "Item[]", "t.both": "B", "t.plain": "P", "t.raw": "[number, string]", "t.raw_null": "R" },
      imports: ["// imports"],
      comments: false,
    });
    expect(source).toBe(`// Generated by \`typesql introspect\` (@typesql/pg) from PostgreSQL 17. Do not edit.
import type { Col, Generated, Json } from "@typesql/core";
// imports

export interface DB {
  t: {
    id: Generated<"int4">;
    doc: Json<{ a: number }, { nullable: true }>;
    items: Json<Item[], { hasDefault: true }>;
    both: Json<B, { nullable: true; hasDefault: true }>;
    plain: Json<P>;
    raw: Json<[number, string], {}, "json">;
    raw_null: Json<R, { nullable: true }, "json">;
    other: Col<"jsonb">;
  };
}
`);
    expect(() => generateSource(db(), { columnTypes: { "t.nope": "X" } })).toThrow('columnTypes: no column "t.nope"');
    expect(() => generateSource(db(), { columnTypes: { "t.id": "UserId" } }))
      .toThrow('columnTypes: "t.id" has type int4; columnTypes only types json / jsonb columns (use the column hook for others)');
    const arrays = db({ relations: [{ schema: "public", name: "t", kind: "table", comment: null, columns: [col("docs", "jsonb[]")] }] });
    expect(() => generateSource(arrays, { columnTypes: { "t.docs": "X[]" } })).toThrow('"t.docs" has type jsonb[]');
  });

  test("columnTypes as a function, e.g. reading a type from the column comment", () => {
    const source = generateSource(db({
      schemas: ["public", "app"],
      relations: [
        { schema: "public", name: "t", kind: "table", comment: null, columns: [col("doc", "jsonb", { comment: "@type Doc[]" }), col("n", "int4")] },
        { schema: "app", name: "u", kind: "table", comment: null, columns: [col("meta", "jsonb", { nullable: true, comment: "@type Meta" })] },
        { schema: "app", name: "v", kind: "view", comment: null, columns: [col("meta", "json", { nullable: true, comment: "@type Meta" })] },
      ],
    }), { columnTypes: (c) => /^@type (.+)$/.exec(c.comment ?? "")?.[1], comments: false });
    expect(source).toContain("doc: Json<Doc[]>;");
    expect(source).toContain('n: Col<"int4">;');
    expect(source).toContain("meta: Json<Meta, { nullable: true }>;");
    expect(source).toContain('v: View<{\n      meta: Json<Meta, { nullable: true }, "json">;\n    }>;');
    expect(() => generateSource(db(), { columnTypes: (c) => (c.name === "id" ? "Id" : undefined) })).toThrow('"t.id" has type int4');
  });

  test("the column hook replaces a descriptor", () => {
    const source = generateSource(db(), { column: (c) => (c.type === "jsonb" ? "Json<Doc>" : undefined) });
    expect(source).toContain("doc: Json<Doc>;");
    expect(source).toContain('id: Generated<"int4">;');
  });

  test("enums of the same name in two schemas share one $types entry", () => {
    const source = generateSource(db({
      enums: [
        { schema: "a", name: "status", values: ["on", "off"] },
        { schema: "b", name: "status", values: ["off", "gone"] },
        { schema: "public", name: "empty", values: [] },
      ],
    }));
    expect(source).toContain('    /** Enums of the same name in `a`, `b`. */\n    status: "on" | "off" | "gone";');
    expect(source).toContain("    empty: never;");
  });

  test("a schema named like a public table is an error", () => {
    expect(() => generateSource(db({
      relations: [
        { schema: "public", name: "auth", kind: "table", comment: null, columns: [] },
        { schema: "auth", name: "users", kind: "table", comment: null, columns: [] },
      ],
    }))).toThrow('schema "auth" has the same name as the table "public.auth"');
  });

  test("notes for comments, domains, identity and generated columns", () => {
    const source = generateSource(db({
      relations: [{
        schema: "public", name: "t", kind: "materialized view", comment: "Counts.\nRefreshed hourly.", columns: [
          col("a", "int4", { domain: "public.positive", comment: "An */ amount." }),
          col("b", "int8", { identity: "always", hasDefault: true }),
          col("c", "text", { generated: "upper(x)", hasDefault: true }),
        ],
      }],
    }));
    expect(source).toContain(`  /**
   * Counts.
   * Refreshed hourly.
   * Materialized view.
   */
  t: View<{
    /**
     * An *\\/ amount.
     * Domain \`public.positive\`.
     */
    a: Col<"int4">;
    /** \`GENERATED ALWAYS AS IDENTITY\`: written only with \`OVERRIDING SYSTEM VALUE\`. */
    b: Generated<"int8">;
    /** \`GENERATED ALWAYS AS (upper(x)) STORED\`: cannot be written. */
    c: Generated<"text">;
  }>;`);
  });
});

describe("parseNodeTree", () => {
  test("nodes, lists, bitmapsets, strings, escapes and datums", () => {
    expect(parseNodeTree('({VAR :varno 1 :varnullingrels (b 3) :x <> :name "a b" :alias *SELECT*\\ 2} {CONST :constisnull false :constvalue 4 [ 1 0 0 0 ]})')).toEqual([
      { _: "VAR", varno: "1", varnullingrels: ["b", "3"], x: null, name: "a b", alias: "*SELECT* 2" },
      { _: "CONST", constisnull: "false", constvalue: "4" },
    ]);
  });
});

describe("main", () => {
  const run = async (argv: string[], env: Record<string, string> = {}) => {
    const out: string[] = [];
    const err: string[] = [];
    const code = await main(argv, { stdout: (s) => out.push(s), stderr: (s) => err.push(s), env, cwd: process.cwd() });
    return { code, out: out.join(""), err: err.join("") };
  };

  test("--help, missing command, unknown command, missing url", async () => {
    expect(await run(["--help"])).toMatchObject({ code: 0, out: expect.stringContaining("Usage: typesql introspect") });
    expect(await run([])).toMatchObject({ code: 2, err: expect.stringContaining("Usage:") });
    expect(await run(["generate"])).toMatchObject({ code: 2, err: expect.stringContaining("unknown command: generate") });
    expect(await run(["introspect", "--bogus"])).toMatchObject({ code: 2, err: expect.stringContaining("--bogus") });
    expect(await run(["introspect"])).toMatchObject({ code: 2, err: "typesql introspect: pass --url or set DATABASE_URL\n" });
  });

  test("connection errors exit 1 with the message", async () => {
    const out: string[] = [];
    const code = await main(["introspect", "--url", "postgres://x"], {
      stdout: () => undefined,
      stderr: (s) => out.push(s),
      env: {},
      cwd: process.cwd(),
      connect: async () => { throw new Error("connection refused"); },
    });
    expect(code).toBe(1);
    expect(out.join("")).toBe("typesql introspect: connection refused\n");
  });
});
