import { readFileSync, writeFileSync } from "node:fs";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, beforeAll, describe, expect, test } from "vitest";
import { Client } from "pg";
import { acquireDatabase } from "../../../core/test/conformance/db.js";
import { generateSource, introspect } from "../../src/introspect/index.js";
import { main } from "../../src/introspect/cli.js";
import config from "./introspect.config.js";
import { ddl } from "./fixture.js";

/**
 * `typesql introspect` end to end: build the fixture database in a fresh database of a real
 * Postgres, introspect it and compare with the checked-in `schema.generated.ts` (which
 * `introspect.test-d.ts` type-checks queries against). `TYPESQL_UPDATE_FIXTURES=1` rewrites the
 * file instead. Skips when no database can be obtained (see core's conformance `db.ts`).
 */

const generatedFile = fileURLToPath(new URL("./schema.generated.ts", import.meta.url));
const configFile = fileURLToPath(new URL("./introspect.config.ts", import.meta.url));
/** The header names the server's major version; compare the rest. */
const body = (source: string): string => source.replace(/^\/\/ Generated by .*\n/, "");

const db = await acquireDatabase();
const dbName = `typesql_introspect_${process.pid}`;

describe.skipIf(!db)("typesql introspect against Postgres", () => {
  let admin: Client;
  let client: Client;
  let url: string;

  beforeAll(async () => {
    admin = new Client({ connectionString: db!.url });
    await admin.connect();
    await admin.query(`DROP DATABASE IF EXISTS ${dbName}`);
    await admin.query(`CREATE DATABASE ${dbName}`);
    const u = new URL(db!.url);
    u.pathname = `/${dbName}`;
    url = u.href;
    client = new Client({ connectionString: url });
    await client.connect();
    for (const statement of ddl) await client.query(statement);
  }, 60_000);

  afterAll(async () => {
    await client?.end();
    await admin?.query(`DROP DATABASE IF EXISTS ${dbName}`);
    await admin?.end();
    await db?.close();
  }, 60_000);

  test("the generated schema matches schema.generated.ts", async () => {
    const source = generateSource(await introspect(client, config), config);
    if (process.env["TYPESQL_UPDATE_FIXTURES"]) writeFileSync(generatedFile, source);
    expect(body(source)).toBe(body(readFileSync(generatedFile, "utf8")));
  }, 30_000);

  test("reads columns, defaults, domains, identity and generated columns", async () => {
    const info = await introspect(client, { schemas: ["public", "auth"] });
    expect(info.schemas).toEqual(["public", "auth"]);
    expect(info.relations.map((r) => `${r.schema}.${r.name}:${r.kind}`)).toEqual([
      "public.email_rollup:view",
      "public.events:partitioned table",
      "public.events_2024:table",
      "public.history_points:view",
      "public.user_flags:view",
      "public.user_sessions:view",
      "public.users:table",
      "auth.session_counts:materialized view",
      "auth.sessions:table",
    ]);
    const users = info.relations.find((r) => r.name === "users")!;
    const col = (name: string) => users.columns.find((c) => c.name === name)!;
    expect(col("name")).toMatchObject({ type: "text", nullable: false, domain: "public.short_name", hasDefault: false });
    expect(col("ages")).toMatchObject({ type: "int4[]", nullable: true });
    expect(col("email")).toMatchObject({ type: "text", declaredType: "citext", comment: "Login e-mail. Case-insensitive */ unique." });
    expect(col("big")).toMatchObject({ type: "int8", identity: "always", hasDefault: true, default: null });
    expect(col("serial_no")).toMatchObject({ type: "int4", hasDefault: true, default: "nextval('users_serial_no_seq'::regclass)" });
    expect(col("greeting")).toMatchObject({ hasDefault: true, generated: "('Hello '::text || (name)::text)", default: null });
    expect(col("moods")).toMatchObject({ type: "mood[]", nullable: false, hasDefault: true });
    expect(info.enums).toEqual([
      { schema: "public", name: "mood", values: ["happy", "ok", "sad"] },
      { schema: "auth", name: "role", values: ["member", "admin"] },
    ]);
  }, 30_000);

  test("exclude patterns and viewNotNull", async () => {
    const info = await introspect(client, { exclude: ["events_*", "auth.session_*"], viewNotNull: (view, column) => view === "user_sessions" && column === "token" });
    expect(info.relations.map((r) => `${r.schema}.${r.name}`)).toEqual(["public.email_rollup", "public.events", "public.history_points", "public.user_flags", "public.user_sessions", "public.users", "auth.sessions"]);
    const view = info.relations.find((r) => r.name === "user_sessions")!;
    expect(view.columns.map((c) => [c.name, c.nullable])).toEqual([
      ["id", false], ["email", false], ["name", false], ["token", false], ["role", true],
      ["display", false], ["session_count", false], ["live", true],
    ]);
  }, 30_000);

  test("NOT NULL columns hold no NULLs and every relation has rows", async () => {
    const info = await introspect(client);
    for (const rel of info.relations) {
      const { rows } = await client.query(`SELECT * FROM "${rel.schema}"."${rel.name}"`);
      expect.soft(rows.length, `${rel.schema}.${rel.name} has rows`).toBeGreaterThan(0);
      for (const row of rows) {
        for (const c of rel.columns) {
          if (!c.nullable) expect.soft(row[c.name], `${rel.schema}.${rel.name}.${c.name}`).not.toBeNull();
        }
      }
    }
  }, 30_000);

  test("views that read each other (Postgres allows the cycle) are introspected, as nullable", async () => {
    await client.query("CREATE SCHEMA cyc");
    try {
      await client.query("CREATE VIEW cyc.v1 AS SELECT 1 AS a");
      await client.query("CREATE VIEW cyc.v2 AS SELECT a FROM cyc.v1");
      await client.query("CREATE OR REPLACE VIEW cyc.v1 AS SELECT a FROM cyc.v2");
      const info = await introspect(client, { schemas: ["cyc"] });
      expect(info.relations.map((r) => [r.name, r.columns.map((c) => [c.name, c.nullable])])).toEqual([["v1", [["a", true]]], ["v2", [["a", true]]]]);
    } finally {
      await client.query("DROP SCHEMA cyc CASCADE");
    }
  }, 30_000);

  test("the default schema list skips system schemas, public first", async () => {
    const info = await introspect(client);
    expect(info.schemas).toEqual(["public", "auth"]);
    await expect(introspect(client, { schemas: ["nope"] })).rejects.toThrow('schema "nope" does not exist');
  }, 30_000);

  test("the CLI writes the same file with --config", async () => {
    const dir = await mkdtemp(join(tmpdir(), "typesql-introspect-"));
    try {
      const out = join(dir, "db.ts");
      const stderr: string[] = [];
      const code = await main(["introspect", "--url", url, "--config", configFile, "--out", out], {
        stdout: () => undefined,
        stderr: (s) => stderr.push(s),
        env: {},
        cwd: dir,
      });
      expect(stderr.join("")).toBe(`typesql introspect: wrote ${out}\n`);
      expect(code).toBe(0);
      expect(body(await readFile(out, "utf8"))).toBe(body(readFileSync(generatedFile, "utf8")));
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  }, 30_000);

  test("the CLI prints to stdout and reads DATABASE_URL", async () => {
    const stdout: string[] = [];
    const code = await main(["introspect", "--schema", "auth", "--no-comments", "--type-name", "AuthDB"], {
      stdout: (s) => stdout.push(s),
      stderr: () => undefined,
      env: { DATABASE_URL: url },
      cwd: process.cwd(),
    });
    expect(code).toBe(0);
    expect(body(stdout.join(""))).toBe(`import type { Col, Generated, Nullable, View } from "@typesql/core";

export interface AuthDB {
  auth: {
    session_counts: View<{
      user_id: Col<"uuid">;
      n: Col<"int8">;
      last: Nullable<"timestamptz">;
    }>;
    sessions: {
      token: Col<"uuid">;
      user_id: Col<"uuid">;
      role: Generated<"role">;
      expires_at: Nullable<"timestamptz">;
    };
  };
  $types: {
    role: "member" | "admin";
  };
}
`);
  }, 30_000);
});
